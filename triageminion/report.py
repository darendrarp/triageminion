"""Render a validated TriageReport as maintainer-readable Markdown."""

from __future__ import annotations

from .models import TriageReport

_SEVERITY_EMOJI = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🟢"}


def render_markdown(report: TriageReport, *, provider: str = "unknown", model: str = "unknown") -> str:
    """Render the full report, including a run footer for reproducibility."""
    lines = [
        f"# Triage report — {report.repo}",
        "",
        f"> Generated by TriageMinion (OpenMinion 0.1 Python SDK) · "
        f"provider `{provider}` · model `{model}`",
        "",
        "## Summary",
        "",
        report.summary,
        "",
        "## Verdicts",
        "",
        "| # | Issue | Category | Severity | Priority | Labels | Dup of | Needs info | Conf. |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for issue in report.issues:
        emoji = _SEVERITY_EMOJI.get(issue.severity.lower(), "")
        lines.append(
            f"| #{issue.number} | {issue.title} | {issue.category} | "
            f"{emoji} {issue.severity} | {issue.priority} | "
            f"{', '.join(issue.suggested_labels) or '—'} | "
            f"{'#' + str(issue.duplicate_of) if issue.duplicate_of else '—'} | "
            f"{'yes' if issue.needs_info else 'no'} | {issue.confidence:.2f} |"
        )
    lines += ["", "## Rationale", ""]
    for issue in report.issues:
        lines += [f"### #{issue.number} — {issue.title}", "", issue.rationale, ""]
    lines += [
        "---",
        "",
        "Reproduce: `python -m triageminion "
        f"{report.repo} --limit {len(report.issues)}`",
    ]
    return "\n".join(lines) + "\n"
